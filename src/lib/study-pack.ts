import type { Block, Line, Section } from "@/lib/notes";

function pairs(caption: string, rows: [string, string][]): Block {
  const items: Line[] = rows.map(([es, ar]) => ({ es, ar }));
  return { type: "pairs", caption, items };
}

function talk(
  title: string,
  lines: [string, string, string][],
): Block {
  return {
    type: "dialogue",
    title,
    lines: lines.map(([who, es, ar]) => ({ who, es, ar })),
  };
}

